-- 글 단위 정보와 임베딩 모델을 청크에서 떼어 낸다.
--   search.posts         글 하나에 한 행: 제목, 글 주소
--   search.embed_models  임베딩 모델 이름
--   search.chunks        청크: 글과 모델을 키로 가리킨다. 청크 주소는 posts.href || '#' || anchor
-- 차원은 모델과 무관하게 768 로 고정이다(embedding 컬럼 타입). 기록하지 않는다.
-- 이미 들어 있는 행을 그대로 옮기므로 다시 임베딩하지 않는다.

CREATE TABLE search.embed_models (
    id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE
);

INSERT INTO search.embed_models (name)
SELECT DISTINCT embed_model FROM search.chunks;

CREATE TABLE search.posts (
    post_id  text PRIMARY KEY,
    title    text NOT NULL,
    href     text NOT NULL
);

INSERT INTO search.posts (post_id, title, href)
SELECT DISTINCT ON (post_id) post_id, post_title, split_part(href, '#', 1)
FROM search.chunks
ORDER BY post_id;

ALTER TABLE search.chunks
    ADD COLUMN anchor text,
    ADD COLUMN embed_model_id smallint;

UPDATE search.chunks AS c
SET anchor = CASE WHEN position('#' IN c.href) > 0
                  THEN substr(c.href, position('#' IN c.href) + 1)
                  ELSE '' END,
    embed_model_id = m.id
FROM search.embed_models AS m
WHERE m.name = c.embed_model;

ALTER TABLE search.chunks
    ALTER COLUMN anchor SET NOT NULL,
    ALTER COLUMN embed_model_id SET NOT NULL,
    ADD CONSTRAINT chunks_post_fk
        FOREIGN KEY (post_id) REFERENCES search.posts (post_id) ON DELETE CASCADE,
    ADD CONSTRAINT chunks_embed_model_fk
        FOREIGN KEY (embed_model_id) REFERENCES search.embed_models (id),
    DROP COLUMN post_title,
    DROP COLUMN href,
    DROP COLUMN embed_model,
    DROP COLUMN embed_dim;

GRANT SELECT ON search.posts, search.embed_models TO search_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON search.posts TO search_writer;
GRANT SELECT, INSERT ON search.embed_models TO search_writer;
GRANT USAGE ON SEQUENCE search.embed_models_id_seq TO search_writer;
